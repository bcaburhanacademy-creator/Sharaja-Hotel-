const LANG_KEY = "sharjah_hotel_lang";

export function getCurrentLanguage() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved && (saved === "ur" || saved === "ps" || saved === "en")) {
    return saved;
  }
  return "en";
}

export function setLanguage(lang) {
  if (!["en", "ur", "ps"].includes(lang)) return;
  localStorage.setItem(LANG_KEY, lang);
  applyLanguage(lang);
}

export function applyLanguage(lang) {
  const html = document.documentElement;
  html.setAttribute("lang", lang);

  const isRtl = lang === "ur" || lang === "ps";
  html.setAttribute("dir", isRtl ? "rtl" : "ltr");

  if (isRtl) {
    document.body.classList.add("rtl-mode");
    document.body.classList.remove("ltr-mode");
    if (lang === "ur") {
      document.body.classList.add("lang-ur");
      document.body.classList.remove("lang-ps");
    } else {
      document.body.classList.add("lang-ps");
      document.body.classList.remove("lang-ur");
    }
  } else {
    document.body.classList.add("ltr-mode");
    document.body.classList.remove("rtl-mode", "lang-ur", "lang-ps");
  }

  // Update text contents of elements with [data-i18n]
  const elements = document.querySelectorAll("[data-i18n]");
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.hasAttribute("placeholder")) {
          el.setAttribute("placeholder", dict[key]);
        }
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Update active state in any language dropdown or buttons
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    const targetLang = btn.getAttribute("data-lang-btn");
    if (targetLang === lang) {
      btn.classList.add("active-lang");
    } else {
      btn.classList.remove("active-lang");
    }
  });

  // Dispatch custom event so dynamic components (menu grid, cart, etc.) re-render
  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

// Initialize on page load
document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getCurrentLanguage();
  applyLanguage(initialLang);

  // Setup click listeners for language switchers
  document.querySelectorAll("[data-lang-select]").forEach((selector) => {
    selector.addEventListener("click", (e) => {
      const btn = e.target.closest("[data-lang-btn]");
      if (btn) {
        const selectedLang = btn.getAttribute("data-lang-btn");
        if (selectedLang) {
          setLanguage(selectedLang);
        }
      }
    });
  });

  // Also support <select> element if used
  document.querySelectorAll("select[data-lang-dropdown]").forEach((select) => {
    select.value = initialLang;
    select.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  });
});
